// Tiny pixel-art glyphs, drawn as crisp SVG. '#' = filled.

export function pixelSVG(rows, color = "currentColor") {
  const h = rows.length;
  const w = rows[0].length;
  let d = "";
  rows.forEach((row, y) => {
    let x = 0;
    while (x < w) {
      if (row[x] === "#") {
        let len = 1;
        while (x + len < w && row[x + len] === "#") len++;
        d += `M${x} ${y}h${len}v1h-${len}z`;
        x += len;
      } else x++;
    }
  });
  return `<svg viewBox="0 0 ${w} ${h}" shape-rendering="crispEdges" aria-hidden="true" focusable="false"><path d="${d}" fill="${color}"/></svg>`;
}

// Build a filled disc, then knock pixels out of it.
function disc(size, knock = []) {
  const c = (size - 1) / 2;
  const r = size / 2;
  const rows = [];
  for (let y = 0; y < size; y++) {
    let s = "";
    for (let x = 0; x < size; x++) {
      const inside = (x - c) ** 2 + (y - c) ** 2 <= (r - 0.25) ** 2;
      s += inside ? "#" : ".";
    }
    rows.push(s.split(""));
  }
  knock.forEach(([x, y]) => { if (rows[y]) rows[y][x] = "."; });
  return rows.map((r) => r.join(""));
}


// A round gear: body disc, square teeth, hole in the middle.
function gearGlyph(size, teeth) {
  const c = (size - 1) / 2, rows = [];
  for (let y = 0; y < size; y++) {
    let s = "";
    for (let x = 0; x < size; x++) {
      const dx = x - c, dy = y - c, r = Math.hypot(dx, dy);
      const a = (Math.atan2(dy, dx) + Math.PI * 2) % (Math.PI * 2);
      const onTooth = Math.floor((a / (Math.PI * 2)) * teeth * 2 + 0.5) % 2 === 0;
      const fill = (r <= size * 0.34 || (r <= size / 2 - 0.1 && onTooth)) && r > size * 0.13;
      s += fill ? "#" : ".";
    }
    rows.push(s);
  }
  return rows;
}

// Multi-colour pixel art: each character maps to a colour in the palette, '.' is empty.
export function pixelArt(rows, palette) {
  const w = Math.max(...rows.map((r) => r.length));
  const h = rows.length;
  const paths = {};
  rows.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      const ch = row[x];
      if (ch !== "." && palette[ch]) {
        let len = 1;
        while (x + len < row.length && row[x + len] === ch) len++;
        paths[ch] = (paths[ch] || "") + `M${x} ${y}h${len}v1h-${len}z`;
        x += len;
      } else x++;
    }
  });
  const body = Object.entries(paths).map(([ch, d]) => `<path d="${d}" fill="${palette[ch]}"/>`).join("");
  return `<svg viewBox="0 0 ${w} ${h}" shape-rendering="crispEdges" aria-hidden="true" focusable="false">${body}</svg>`;
}

