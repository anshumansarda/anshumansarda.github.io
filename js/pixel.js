// Tiny pixel-art glyphs, drawn as crisp SVG. '#' = filled.

export function pixelSVG(rows, color = "currentColor") {
  const h = rows.length;
  const w = rows[0].length;
  let d = "";
  rows.forEach((row, y) => {
    let x = 0;
    while (x < w) {
      if (row[x] === "#") {
        let len = 1;
        while (x + len < w && row[x + len] === "#") len++;
        d += `M${x} ${y}h${len}v1h-${len}z`;
        x += len;
      } else x++;
    }
  });
  return `<svg viewBox="0 0 ${w} ${h}" shape-rendering="crispEdges" aria-hidden="true" focusable="false"><path d="${d}" fill="${color}"/></svg>`;
}

// Build a filled disc, then knock pixels out of it.
function disc(size, knock = []) {
  const c = (size - 1) / 2;
  const r = size / 2;
  const rows = [];
  for (let y = 0; y < size; y++) {
    let s = "";
    for (let x = 0; x < size; x++) {
      const inside = (x - c) ** 2 + (y - c) ** 2 <= (r - 0.25) ** 2;
      s += inside ? "#" : ".";
    }
    rows.push(s.split(""));
  }
  knock.forEach(([x, y]) => { if (rows[y]) rows[y][x] = "."; });
  return rows.map((r) => r.join(""));
}

function range(a, b) { const o = []; for (let i = a; i <= b; i++) o.push(i); return o; }

const X16 = (() => {
  const rows = [];
  for (let y = 0; y < 16; y++) {
    let s = "";
    for (let x = 0; x < 16; x++) {
      const thick = Math.abs(x - y) <= 1 && y > 0 && y < 15;
      const thin = Math.abs(x - (15 - y)) === 0 && y > 0 && y < 15;
      s += thick || thin ? "#" : ".";
    }
    rows.push(s);
  }
  return rows;
})();

const SPOTIFY = disc(16, [
  ...range(3, 11).map((x) => [x, 4]), [12, 5], [11, 5],
  ...range(4, 10).map((x) => [x, 7]), [11, 8],
  ...range(5, 9).map((x) => [x, 10]), [10, 11],
]);

