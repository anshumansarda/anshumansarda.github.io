export function paintGlyphs(root = document) {
  root.querySelectorAll("[data-glyph]").forEach((el) => {
    const g = GLYPHS[el.dataset.glyph];
    if (g && !el.firstChild) el.innerHTML = pixelSVG(g);
  });
}
